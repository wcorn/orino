package ds.project.orino.domain.planner.ledger.entity;

/**
 * 고정비인가 변동비인가(`LDG-061`).
 *
 * <p>이 구분이 있어야 「절약 여지가 어디에 있나」에 답할 수 있다. 고정비 비중이 계속 오르면
 * 커피를 줄일 게 아니라 <b>정기 항목을 정리해야</b> 하고, 그 판단은 변동비만 보는 화면에서는
 * 절대 나오지 않는다.
 *
 * <p>카테고리에 붙는다. 거래마다 정하게 하면 같은 카테고리가 어떤 달에는 고정비, 어떤 달에는
 * 변동비가 되어 추이가 의미를 잃는다.
 */
public enum LedgerCostType {

    /** 매달 비슷하게 나가는 것 — 주거·통신·보험·구독. */
    FIXED,

    /** 쓰기 나름인 것 — 식비·카페·문화. */
    VARIABLE
}
